"""Build and validate EphemerisPack artefacts from parsed Horizons tracks.

An ``EphemerisPack`` combines the Sun and Earth topocentric tracks for one curated
site into a single runtime artefact (REQ-06, REQ-07). It is generated by
``src.cli.build_ephemeris_packs`` and read by the API; it is not a wire contract.

``source_manifest_sha256`` is the SHA-256 over the byte streams of the two source
Horizons manifests, concatenated in ascending path order, so the provenance of a
pack can be recomputed from the tracked manifests alone.
"""

from __future__ import annotations

import hashlib
import json
import math
from collections.abc import Mapping, Sequence
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any, Protocol

SCHEMA_VERSION = 1
FRAME = "MOON_ME"
LONGITUDE_CONVENTION = "east_positive"
AZIMUTH_CONVENTION = "clockwise_from_north"
ARRAY_KEYS = ("sun_az_deg", "sun_elev_deg", "earth_az_deg", "earth_elev_deg")


class EphemerisPackError(ValueError):
    """Raised when source rows or a built pack violate the EphemerisPack contract."""


class SampleRow(Protocol):
    """Minimal read-only row shape shared with the Horizons parser."""

    @property
    def utc(self) -> datetime: ...

    @property
    def az_deg(self) -> float: ...

    @property
    def elev_deg(self) -> float: ...


def sha256_file(path: Path) -> str:
    """Return the SHA-256 of a file's bytes."""
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def combined_manifest_sha256(paths: Sequence[Path]) -> str:
    """Return the SHA-256 of the source manifest files concatenated in path order."""
    digest = hashlib.sha256()
    for path in sorted(Path(item) for item in paths):
        with path.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1 << 20), b""):
                digest.update(chunk)
    return digest.hexdigest()


def _require_utc(value: datetime, label: str) -> None:
    """Reject a naive timestamp; every pack time is UTC-only (REQ-07)."""
    if value.tzinfo is None or value.utcoffset() != timedelta(0):
        raise EphemerisPackError(f"{label} must be a UTC-aware datetime; got {value!r}")


def _validate_track(
    label: str,
    rows: Sequence[SampleRow],
    *,
    sample_count: int,
    start_utc: datetime,
    step_seconds: int,
) -> None:
    """Prove a track has the locked sample count and an exact hourly grid."""
    if len(rows) != sample_count:
        raise EphemerisPackError(f"{label} track has {len(rows)} rows, expected {sample_count}")
    for index, row in enumerate(rows):
        expected = start_utc + timedelta(seconds=index * step_seconds)
        if row.utc != expected:
            raise EphemerisPackError(f"{label} row {index} is {row.utc}, expected {expected}")
        _check_sample(f"{label}[{index}]", row.az_deg, row.elev_deg)


def _check_sample(label: str, az_deg: float, elev_deg: float) -> None:
    """Reject a sample outside the documented azimuth and elevation ranges."""
    if not math.isfinite(az_deg) or not math.isfinite(elev_deg):
        raise EphemerisPackError(f"{label} has a non-finite azimuth or elevation")
    if not 0.0 <= az_deg < 360.0:
        raise EphemerisPackError(f"{label} azimuth {az_deg} is outside [0, 360)")
    if not -90.0 <= elev_deg <= 90.0:
        raise EphemerisPackError(f"{label} elevation {elev_deg} is outside [-90, 90]")


def build_ephemeris_pack(
    *,
    site_id: str,
    sun_rows: Sequence[SampleRow],
    earth_rows: Sequence[SampleRow],
    start_utc: datetime,
    stop_utc: datetime,
    step_seconds: int,
    source_manifest_sha256: str,
    site_coord_used: Mapping[str, float],
) -> dict[str, Any]:
    """Assemble a validated EphemerisPack from the two Horizons tracks."""
    _require_utc(start_utc, "start_utc")
    _require_utc(stop_utc, "stop_utc")
    if step_seconds <= 0:
        raise EphemerisPackError("step_seconds must be positive")
    span = (stop_utc - start_utc).total_seconds()
    if span <= 0 or span % step_seconds != 0:
        raise EphemerisPackError(
            f"coverage span {span}s is not a positive multiple of {step_seconds}s"
        )
    sample_count = int(span // step_seconds) + 1
    _validate_track(
        "sun", sun_rows, sample_count=sample_count, start_utc=start_utc, step_seconds=step_seconds
    )
    _validate_track(
        "earth",
        earth_rows,
        sample_count=sample_count,
        start_utc=start_utc,
        step_seconds=step_seconds,
    )
    if len(source_manifest_sha256) != 64:
        raise EphemerisPackError("source_manifest_sha256 must be a hex SHA-256 digest")

    pack: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "site_id": site_id,
        "frame": FRAME,
        "longitude_convention": LONGITUDE_CONVENTION,
        "azimuth_convention": AZIMUTH_CONVENTION,
        "start_utc": start_utc.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "stop_utc": stop_utc.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "step_seconds": step_seconds,
        "sample_count": sample_count,
        "sun_az_deg": [float(row.az_deg) for row in sun_rows],
        "sun_elev_deg": [float(row.elev_deg) for row in sun_rows],
        "earth_az_deg": [float(row.az_deg) for row in earth_rows],
        "earth_elev_deg": [float(row.elev_deg) for row in earth_rows],
        "source_manifest_sha256": source_manifest_sha256,
        "site_coord_used": dict(site_coord_used),
    }
    validate_ephemeris_pack(pack)
    return pack


def validate_ephemeris_pack(pack: Mapping[str, Any]) -> None:
    """Raise EphemerisPackError if any REQ-06 EphemerisPack invariant is violated."""
    if pack.get("schema_version") != SCHEMA_VERSION:
        raise EphemerisPackError("schema_version must be 1")
    if not pack.get("site_id"):
        raise EphemerisPackError("site_id is required")
    if pack.get("frame") != FRAME:
        raise EphemerisPackError(f"frame must be {FRAME}")
    if pack.get("longitude_convention") != LONGITUDE_CONVENTION:
        raise EphemerisPackError(f"longitude_convention must be {LONGITUDE_CONVENTION}")
    if pack.get("azimuth_convention") != AZIMUTH_CONVENTION:
        raise EphemerisPackError(f"azimuth_convention must be {AZIMUTH_CONVENTION}")
    step_seconds = pack.get("step_seconds")
    if not isinstance(step_seconds, int) or step_seconds <= 0:
        raise EphemerisPackError("step_seconds must be a positive integer")
    start_utc = _parse_pack_time(pack.get("start_utc"), "start_utc")
    stop_utc = _parse_pack_time(pack.get("stop_utc"), "stop_utc")
    span = (stop_utc - start_utc).total_seconds()
    if span <= 0 or span % step_seconds != 0:
        raise EphemerisPackError("pack coverage is not a positive multiple of step_seconds")
    sample_count = pack.get("sample_count")
    if not isinstance(sample_count, int) or sample_count != int(span // step_seconds) + 1:
        raise EphemerisPackError("sample_count does not equal (stop - start) / step + 1")
    if (
        not isinstance(pack.get("source_manifest_sha256"), str)
        or len(pack["source_manifest_sha256"]) != 64
    ):
        raise EphemerisPackError("source_manifest_sha256 must be a hex SHA-256 digest")
    for key in ARRAY_KEYS:
        values = pack.get(key)
        if not isinstance(values, list) or len(values) != sample_count:
            raise EphemerisPackError(f"{key} must have exactly {sample_count} values")
        for index, value in enumerate(values):
            if not isinstance(value, (int, float)) or not math.isfinite(value):
                raise EphemerisPackError(f"{key}[{index}] is not a finite number")
            if key.endswith("_az_deg") and not 0.0 <= float(value) < 360.0:
                raise EphemerisPackError(f"{key}[{index}] is outside [0, 360)")
            if key.endswith("_elev_deg") and not -90.0 <= float(value) <= 90.0:
                raise EphemerisPackError(f"{key}[{index}] is outside [-90, 90]")
    coord = pack.get("site_coord_used")
    if not isinstance(coord, Mapping) or set(coord) != {"lon_deg", "lat_deg", "altitude_km"}:
        raise EphemerisPackError("site_coord_used must contain lon_deg, lat_deg, and altitude_km")


def _parse_pack_time(value: Any, label: str) -> datetime:
    """Parse a pack timestamp, requiring the ISO-8601 Z form."""
    if not isinstance(value, str) or not value.endswith("Z"):
        raise EphemerisPackError(f"{label} must be an ISO-8601 UTC string")
    try:
        return datetime.fromisoformat(value.removesuffix("Z")).replace(tzinfo=UTC)
    except ValueError as exc:
        raise EphemerisPackError(f"{label} is not a valid timestamp: {value!r}") from exc


def write_ephemeris_pack(path: Path, pack: Mapping[str, Any]) -> str:
    """Write a validated pack deterministically and return the file's SHA-256."""
    validate_ephemeris_pack(pack)
    payload = json.dumps(dict(pack), separators=(",", ":"), allow_nan=False) + "\n"
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(payload, encoding="utf-8")
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def load_ephemeris_pack(path: Path) -> dict[str, Any]:
    """Read and validate a pack file."""
    pack = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(pack, dict):
        raise EphemerisPackError(f"{path} does not contain a JSON object")
    validate_ephemeris_pack(pack)
    return pack
